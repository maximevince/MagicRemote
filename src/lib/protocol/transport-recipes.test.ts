import { describe, expect, it } from 'vitest';
import { decodePacket, toHex } from './codec.ts';
import { buildRecordPacket, TransportMode } from './transport-recipes.ts';

// The first 10.1 the Pocket 6K G2 reported: preview, speed 0, flags 0x10 (disk3), media CFast/SD/USB.
const G2_TRANSPORT = [0, 0, 16, 0, 1, 3];

describe('record recipes', () => {
	it('B is the static mode-byte-only packet', () => {
		expect(toHex(buildRecordPacket('B', TransportMode.record, G2_TRANSPORT).bytes)).toBe('ff0500000a01010002000000');
		expect(toHex(buildRecordPacket('B', TransportMode.preview, null).bytes)).toBe('ff0500000a01010000000000');
	});

	it('A echoes the last 10.1 with only the mode changed', () => {
		const r = buildRecordPacket('A', TransportMode.record, G2_TRANSPORT);
		expect(r.recipe).toBe('A');
		// Same bytes m0.py record_packet('A', 2) produces for this state.
		expect(toHex(r.bytes)).toBe('ff0a00000a010100020010000103' + '0000');
		const d = decodePacket(r.bytes);
		expect(d.op).toBe('assign');
		expect(d.values).toEqual([2, 0, 16, 0, 1, 3]);
	});

	it('A-prime also clears speed and the loop/play-all flags', () => {
		const playing = [1, 2, 0x10 | 0x01 | 0x02, 0, 1, 3];
		const a = decodePacket(buildRecordPacket('A', TransportMode.record, playing).bytes);
		expect(a.values).toEqual([2, 2, 0x13, 0, 1, 3]);
		const ap = buildRecordPacket('A-prime', TransportMode.record, playing);
		expect(ap.recipe).toBe('A-prime');
		expect(decodePacket(ap.bytes).values).toEqual([2, 0, 0x10, 0, 1, 3]);
	});

	it('keeps signed speed and the time-lapse bit intact', () => {
		// speed −2 (backwards ×2), flags 0x80 | 0x20 | 0x01 as the camera reports them (signed int8)
		const state = [1, -2, -95, 1, 1];
		expect(decodePacket(buildRecordPacket('A', TransportMode.preview, state).bytes).values).toEqual([0, -2, -95, 1, 1]);
		// 0xa1 & ~0x03 = 0xa0 = −96
		expect(decodePacket(buildRecordPacket('A-prime', TransportMode.record, state).bytes).values).toEqual([2, 0, -96, 1, 1]);
		// unsigned input gives the same bytes
		expect(buildRecordPacket('A', TransportMode.preview, [1, 254, 0xa1, 1, 1]).bytes).toEqual(
			buildRecordPacket('A', TransportMode.preview, state).bytes
		);
	});

	it('A and A-prime fall back to B before any 10.1 has been received', () => {
		for (const recipe of ['A', 'A-prime'] as const) {
			const r = buildRecordPacket(recipe, TransportMode.record, null);
			expect(r.recipe).toBe('B');
			expect(toHex(r.bytes)).toBe('ff0500000a01010002000000');
			expect(buildRecordPacket(recipe, TransportMode.record, []).recipe).toBe('B');
		}
	});

	it('matches record_packet in tools/capture/m0.py byte for byte', () => {
		// Generated by running m0.py's record_packet against the same last_transport values.
		const cases: [Parameters<typeof buildRecordPacket>[0], 0 | 2, number[] | null, string][] = [
			['A', 2, [0, 0, 16, 0, 1, 3], 'ff0a00000a0101000200100001030000'],
			['A-prime', 2, [1, 2, 19, 0, 1, 3], 'ff0a00000a0101000200100001030000'],
			['A-prime', 2, [1, 254, 161, 1, 1], 'ff0900000a0101000200a00101000000'],
			['A', 0, [1, 254, 161, 1, 1], 'ff0900000a01010000fea10101000000'],
			['A', 2, null, 'ff0500000a01010002000000']
		];
		for (const [recipe, mode, state, expected] of cases) {
			expect(toHex(buildRecordPacket(recipe, mode, state).bytes)).toBe(expected);
		}
	});

	it('does not mutate the caller state', () => {
		const state = [1, 2, 3, 0, 1];
		buildRecordPacket('A-prime', TransportMode.record, state);
		expect(state).toEqual([1, 2, 3, 0, 1]);
	});
});
